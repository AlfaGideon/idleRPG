#!/usr/bin/env node
/**
 * Copy the Twemoji SVG assets used by the game into public/icons/emoji and
 * regenerate src/art/icons.ts (emoji -> file name map + emojify helper).
 *
 * Run with: npm run icons
 * Twemoji graphics: CC-BY 4.0 — see README for attribution.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, unlinkSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const TWEMOJI = join(ROOT, 'node_modules', '@twemoji', 'svg');
const OUT = join(ROOT, 'public', 'icons', 'emoji');

if (!existsSync(TWEMOJI)) {
  console.error('@twemoji/svg is missing. Run `npm install` first.');
  process.exit(1);
}

function tsFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? tsFiles(p) : e.name.endsWith('.ts') ? [p] : [];
  });
}

/** Group consecutive emoji-ish code points into a single emoji grapheme. */
function extractEmoji(text) {
  const found = new Set();
  const chars = Array.from(text);
  let i = 0;
  const isPicto = (c) => /\p{Extended_Pictographic}/u.test(c);
  const isJoin = (c) => c === '\uFE0F' || c === '\u200D' || c === '\u20E3'
    || /\p{Emoji_Modifier}/u.test(c);
  while (i < chars.length) {
    const c = chars[i];
    const keycap = /[0-9#*]/.test(c) && (chars[i + 1] === '\uFE0F' || chars[i + 1] === '\u20E3') && chars.slice(i, i + 3).includes('\u20E3');
    if (isPicto(c) || keycap) {
      let j = i + 1;
      while (j < chars.length && (isPicto(chars[j]) || isJoin(chars[j]) || (keycap && /[0-9#*]/.test(chars[j])))) j++;
      found.add(chars.slice(i, j).join('').replace(/\uFE0F+$/, ''));
      i = j;
    } else {
      i++;
    }
  }
  return [...found];
}

function codePoint(seq) {
  const hasZwj = seq.includes('\u200D');
  const parts = [];
  for (const ch of seq) {
    if (ch === '\uFE0F' && !hasZwj) continue;
    parts.push(ch.codePointAt(0).toString(16));
  }
  return parts.join('-');
}

const wanted = new Set();
for (const file of tsFiles(SRC)) {
  for (const e of extractEmoji(readFileSync(file, 'utf8'))) wanted.add(e);
}
for (const e of ['🪙', '🔥', '👑', '⚔️', '🚩', '🏆', '⚠️', '💡', '✨', '📯']) wanted.add(e.replace(/\uFE0F+$/, ''));

mkdirSync(OUT, { recursive: true });
const map = {};
const missing = [];
for (const emoji of [...wanted].sort()) {
  let file = codePoint(emoji);
  if (!existsSync(join(TWEMOJI, `${file}.svg`)) && existsSync(join(TWEMOJI, `${file}-fe0f.svg`))) file += '-fe0f';
  if (!existsSync(join(TWEMOJI, `${file}.svg`))) { missing.push(`${emoji} (${file})`); continue; }
  copyFileSync(join(TWEMOJI, `${file}.svg`), join(OUT, `${file}.svg`));
  map[emoji] = file;
}

for (const f of readdirSync(OUT)) {
  if (f.endsWith('.svg') && !Object.values(map).includes(f.replace(/\.svg$/, ''))) unlinkSync(join(OUT, f));
}

writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(Object.values(map).map((f) => `${f}.svg`).sort()));

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const pattern = Object.keys(map).sort((a, b) => b.length - a.length).map(escapeRe).join('|');

// The generated module has no nested template literals on purpose: it also
// serves the single-file offline build, where __EMOJI_INLINE__ holds data URIs.
const content = `/* AUTO-GENERATED by scripts/prepare-emoji.mjs — do not edit by hand. */
/** Emoji grapheme -> Twemoji SVG file name (without extension). */
export const EMOJI: Record<string, string> = ${JSON.stringify(map, null, 2)};

const EMOJI_RE = new RegExp('${pattern.replace(/'/g, "\\'")}', 'g');

type InlineMap = Record<string, string>;

/**
 * The standalone single-file build injects globalThis.__EMOJI_INLINE__ (file
 * name -> data URI) so no external SVG requests are needed on file:// URLs.
 */
function iconUrl(file: string): string {
  const inline = (globalThis as unknown as { __EMOJI_INLINE__?: InlineMap }).__EMOJI_INLINE__;
  return inline && inline[file] ? inline[file] : './icons/emoji/' + file + '.svg';
}

/** Inline an <img> for every known emoji inside an HTML string. */
export function emojify(html: string): string {
  return html.replace(EMOJI_RE, (m) => {
    const file = EMOJI[m];
    return file
      ? '<img class="emoji" src="' + iconUrl(file) + '" alt="' + m + '" draggable="false">'
      : m;
  });
}

/** Single icon helper for dynamic markup. */
export function icon(char: string, className = ''): string {
  const file = EMOJI[char] ?? EMOJI[char.replace(/\\uFE0F+$/, '')];
  return file
    ? '<img class="emoji ' + className + '" src="' + iconUrl(file) + '" alt="' + char + '" draggable="false">'
    : char;
}
`;
writeFileSync(join(SRC, 'art', 'icons.ts'), content);

console.log(`Copied ${Object.keys(map).length} emoji SVGs to ${relative(ROOT, OUT)}`);
if (missing.length) console.warn('Not found in Twemoji:', missing.join(', '));
